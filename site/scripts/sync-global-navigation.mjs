import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const sourceRoot = process.argv.find((argument) => argument.startsWith("--source="))?.slice("--source=".length);
assert.ok(sourceRoot, "Pass --source=/path/to/FDLC to sync the canonical global navigation.");
const source = await readFile(path.resolve(sourceRoot, "lib/global-navigation.ts"), "utf8");
const destination = new URL("../lib/global-navigation.generated.ts", import.meta.url);
const generated = `// Generated by scripts/sync-global-navigation.mjs from FDLC/lib/global-navigation.ts. Do not edit.\n${source}`;

if (process.argv.includes("--check")) {
  assert.equal(await readFile(destination, "utf8"), generated, "Guide global navigation has drifted from FDLC. Run the sync command.");
  console.log("Guide global navigation matches FDLC.");
} else {
  await writeFile(destination, generated);
  console.log("Updated Guide global navigation from FDLC.");
}
